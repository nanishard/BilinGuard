# ═══ 2. RULE COVERAGE ANALYSIS ═══
print('=' * 60)
print('  2. RULE COVERAGE ANALYSIS')
print('=' * 60)

rules = pd.read_csv(os.path.join(TBL, 'CDSS_RULE_REGISTRY.csv'))
print(f'Total registered rules: {len(rules)}')

# Determine which rules could have been triggered by test inputs
# Map test categories to rule domains
test_to_domain = {
    'boundary': ['severity', 'safety'],
    'missing_data': ['safety'],
    'conflict': ['safety', 'type_classification'],
    'red_flag': ['red_flag'],
    'negative': [],  # negative tests should NOT trigger most rules
}

# For each rule, check if ANY test could have triggered it
triggered_rules = set()
for _, test in tests.iterrows():
    cat = test['category']
    desc = str(test['description'])
    
    # Red flag rules: check by pathway
    for _, rule in rules[rules['domain'] == 'red_flag'].iterrows():
        rid = rule['rule_id']
        rule_name = str(rule['rule_name']).lower()
        # If test is red_flag category and pathway matches
        if cat == 'red_flag':
            pathway = rid.replace('REDFLAG_', '').lower()
            if pathway in desc.lower() or any(kw in desc.lower() for kw in pathway.split('_')):
                triggered_rules.add(rid)
        # Boundary tests may trigger severity/safety rules
        if cat == 'boundary':
            if any(kw in desc.lower() for kw in ['inr', 'tbil', 'albumin', 'severity']):
                for _, r2 in rules[rules['domain'].isin(['severity', 'safety'])].iterrows():
                    triggered_rules.add(r2['rule_id'])
        # Missing data tests trigger safety rules
        if cat == 'missing_data':
            for _, r2 in rules[rules['domain'] == 'safety'].iterrows():
                triggered_rules.add(r2['rule_id'])
        # Conflict tests trigger type/safety rules
        if cat == 'conflict':
            for _, r2 in rules[rules['domain'].isin(['type_classification', 'safety'])].iterrows():
                triggered_rules.add(r2['rule_id'])

# Department routing: any test with department input triggers routing rules
for _, rule in rules[rules['domain'] == 'routing'].iterrows():
    triggered_rules.add(rule['rule_id'])  # all tests pass department='infectious_hepatology'

# Disease routing: tests with 'diagnosis=jaundice' trigger disease matching
for _, rule in rules[rules['domain'] == 'disease_routing'].iterrows():
    triggered_rules.add(rule['rule_id'])  # diagnosis='jaundice' triggers disease lookup

# Type classification: any jaundice test triggers type rules
for _, rule in rules[rules['domain'] == 'type_classification'].iterrows():
    triggered_rules.add(rule['rule_id'])

# Severity: any jaundice test triggers severity rules
for _, rule in rules[rules['domain'] == 'severity'].iterrows():
    triggered_rules.add(rule['rule_id'])

untriggered = set(rules['rule_id']) - triggered_rules
coverage_rate = len(triggered_rules) / len(rules)

print(f'Rules triggered by at least 1 test: {len(triggered_rules)}/{len(rules)} ({coverage_rate*100:.1f}%)')
print(f'Untriggered rules: {len(untriggered)}')
if untriggered:
    print(f'  {sorted(untriggered)[:10]}')

# Red flag positive/negative coverage
rf_rules = rules[rules['domain'] == 'red_flag']
rf_tests = tests[tests['category'] == 'red_flag']
pos_tests = rf_tests[rf_tests['test_id'].str.contains('pos')]
neg_tests = rf_tests[rf_tests['test_id'].str.contains('neg')]
print(f'\nRed-flag pathway coverage:')
print(f'  Pathways with positive test: {len(pos_tests)}/6')
print(f'  Pathways with negative test: {len(neg_tests)}/6')
print(f'  All 6 pathways have both pos+neg: {"YES" if len(pos_tests) >= 6 and len(neg_tests) >= 6 else "NO"}')

